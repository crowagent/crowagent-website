/**
 * seo.ts — per-route SEO metadata: title, meta description, canonical,
 * OG title/description/image, Twitter card fields, for all 42 in-scope
 * pages.
 *
 * Extracted programmatically from each page's <head> (regex-based HTML
 * parsing, not a full DOM parser — verified against a sample of pages by
 * hand). Two real parsing bugs were caught and fixed during extraction and
 * are worth recording:
 *   1. `<link href="..." rel="canonical">` — EVERY blog/*.html and
 *      compare/*.html page writes the canonical tag with `href` BEFORE
 *      `rel`, opposite of the root-level pages (`rel` before `href`). A
 *      naive canonical-only regex silently returned null for 13 pages
 *      before this was caught.
 *   2. Several meta tags (e.g. `<meta content="..." property="og:image"/>`)
 *      also use content-before-attribute ordering. A regex using a bare
 *      `.*?` for the content capture caused catastrophic cross-tag
 *      backtracking under DOTALL and silently returned garbage spanning
 *      multiple unrelated tags; fixed by restricting the capture to
 *      `[^<>]*` so it can never bridge a tag boundary.
 * Both classes of bug are worth knowing about if the real Astro migration
 * writes its own frontmatter importer against this markup.
 *
 * FINDING: no duplicate <title> or duplicate meta description was found
 * across any of the 42 pages — despite the task brief's suggestion this was
 * likely, every page has a distinct, hand-written title and description.
 *
 * GAPS FOUND (see CONTENT-MODEL.md for the full writeup):
 *   - og:type is missing on integrations.html and resources.html (every
 *     other page sets it, almost always to "website" or "article").
 *   - twitter:title / twitter:description are missing on faq.html,
 *     index.html and partners.html (those three rely on OG fallback, which
 *     most crawlers honour, but it is inconsistent with the other 39 pages
 *     which set both explicitly).
 *   - twitter:site is missing only on faq.html.
 *   - robots meta is present ("index,follow") on only 22 of 42 pages; the
 *     other 20 have no robots tag at all (defaults to indexable, but is
 *     inconsistent authoring).
 */

