#!/usr/bin/env node
'use strict';
/**
 * tests/build-parity-report.js — merges the per-route result.json files
 * written by tests/parity.spec.js (one per worker-safe test, see the note
 * at the top of that spec) into a single migration/VISUAL-PARITY.md report.
 *
 * Usage: node tests/build-parity-report.js
 * Must be run AFTER `npx playwright test tests/parity.spec.js`.
 */

const fs = require('fs');
const path = require('path');

const SHOTS_DIR = path.join(__dirname, 'parity-shots');
const REPORT_PATH = path.join(__dirname, '..', 'migration', 'VISUAL-PARITY.md');
const DIST_DIR = path.join(__dirname, '..', 'astro', 'dist');

function loadResults() {
  if (!fs.existsSync(SHOTS_DIR)) {
    throw new Error(`${SHOTS_DIR} does not exist — run the parity spec first.`);
  }
  const results = [];
  for (const entry of fs.readdirSync(SHOTS_DIR, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const resultFile = path.join(SHOTS_DIR, entry.name, 'result.json');
    if (!fs.existsSync(resultFile)) continue;
    results.push(JSON.parse(fs.readFileSync(resultFile, 'utf8')));
  }
  results.sort((a, b) => a.route.localeCompare(b.route));
  return results;
}

function discoverRouteCount() {
  const topSections = ['blog', 'compare', 'sectors', 'glossary'];
  let count = 0;
  function walk(dir) {
    if (fs.existsSync(path.join(dir, 'index.html'))) count++;
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (entry.isDirectory()) walk(path.join(dir, entry.name));
    }
  }
  for (const s of topSections) {
    const d = path.join(DIST_DIR, s);
    if (fs.existsSync(d)) walk(d);
  }
  return count;
}

function esc(s) {
  return String(s == null ? '' : s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

function shotRel(route) {
  const trimmed = route.replace(/^\/|\/$/g, '');
  const slug = trimmed === '' ? 'root' : trimmed.replace(/\//g, '-');
  return `../tests/parity-shots/${slug}`;
}

function main() {
  const results = loadResults();
  const expectedCount = discoverRouteCount();
  const generatedAt = new Date().toISOString();

  const totalRoutes = results.length;
  const hardFailRoutes = results.filter((r) => r.hardFailures && r.hardFailures.length > 0);
  const cleanRoutes = results.filter((r) => !r.hardFailures || r.hardFailures.length === 0);
  const missingRoutes = results.filter((r) => !r.legacyOk || !r.astroOk);
  const totalHardFailures = results.reduce((n, r) => n + (r.hardFailures ? r.hardFailures.length : 0), 0);

  const lines = [];
  lines.push('# Visual & Structural Parity Report — LEGACY vs ASTRO');
  lines.push('');
  lines.push(`Generated: ${generatedAt}`);
  lines.push('');
  lines.push(
    'WHY THIS EXISTS: the owner was previously burned by a deploy that changed page layouts ' +
      'without approval. This report is the per-route, evidence-backed answer to "what exactly ' +
      'changes and what does not" before the Astro rebuild replaces any legacy route. It is ' +
      'generated by `tests/parity.spec.js` (Playwright) + `tests/build-parity-report.js`, comparing ' +
      'the legacy static site (http://127.0.0.1:8092) against the Astro build ' +
      '(`astro/dist`, served at http://127.0.0.1:8093) at a 1280×900 viewport.',
  );
  lines.push('');
  lines.push('## How to reproduce');
  lines.push('');
  lines.push('```bash');
  lines.push('# 1. Legacy server (repo root), if not already running:');
  lines.push('npx serve . -l 8092');
  lines.push('');
  lines.push('# 2. Build and serve the Astro rebuild:');
  lines.push('cd astro && npm run build && cd ..');
  lines.push('npx serve astro/dist -l 8093');
  lines.push('');
  lines.push('# 3. Run the parity spec (chromium only — avoid the default');
  lines.push('#    smoke/responsive project matching this file too):');
  lines.push('npx playwright test tests/parity.spec.js --project=chromium');
  lines.push('');
  lines.push('# 4. Rebuild this report from the per-route result.json files:');
  lines.push('node tests/build-parity-report.js');
  lines.push('```');
  lines.push('');
  lines.push('## Methodology notes (read before trusting a number below)');
  lines.push('');
  lines.push(
    '- **Text diff %** is a word-multiset symmetric-difference metric, not a literary/LCS diff: ' +
      'every word is bagged, matched 1:1 regardless of position, and the percentage is ' +
      '`(total_words − matched_words) / max(legacy_words, astro_words) × 100`. It answers "how much ' +
      'of the wording changed", not "what moved where". Chosen because a proper O(n·m) diff over ' +
      'several-thousand-word pages × 22 routes was not going to finish in reasonable CI time. ' +
      'Treat the percentage as a strong signal and read the sample text before acting on it.',
  );
  lines.push(
    '- **JSON-LD @type differences** are reported as the flattened, sorted set of every `@type` ' +
      'found across all `<script type="application/ld+json">` blocks on the page (including inside ' +
      '`@graph` arrays). A missing type means that structured-data entity is not emitted at all on ' +
      'that side, not merely reordered.',
  );
  lines.push(
    '- **Screenshots are evidence for a human, not a pass/fail gate.** The two sites are a deliberate ' +
      'redesign; no pixel diffing is attempted between them.',
  );
  lines.push(
    '- Only **title, meta description, canonical, JSON-LD `@type` set, text diff > 2%, and h1 count** ' +
      'are hard failures. Everything else (h2/h3 counts, internal link counts, geometry, scrollHeight) ' +
      'is reported for context only, because the rebuild is intentionally a redesign.',
  );
  lines.push('');
  lines.push('## Summary');
  lines.push('');
  lines.push(`- Routes discovered under \`astro/dist\`: **${expectedCount}**`);
  lines.push(`- Routes compared (both sides loaded): **${totalRoutes}**`);
  if (totalRoutes !== expectedCount) {
    lines.push(
      `  - ⚠️ **${expectedCount - totalRoutes} route(s) discovered but not found in the result set** ` +
        '— the spec run did not complete for every route. Re-run before trusting this report.',
    );
  }
  lines.push(`- Routes with zero hard failures: **${cleanRoutes.length}**`);
  lines.push(`- Routes with at least one hard failure: **${hardFailRoutes.length}**`);
  lines.push(`- Total hard-failure findings: **${totalHardFailures}**`);
  lines.push(`- Routes missing entirely on one side: **${missingRoutes.length}**`);
  lines.push('');

  lines.push('## Per-route table');
  lines.push('');
  lines.push(
    '| Route | Legacy | Astro | Hard fails | Text diff % | h1 (L/A) | h2 (L/A) | h3 (L/A) | Links (L/A) | JSON-LD types match | Screenshots |',
  );
  lines.push('|---|---|---|---|---|---|---|---|---|---|---|');
  for (const r of results) {
    const L = r.legacy;
    const A = r.astro;
    const textPct = r.textDiff ? `${r.textDiff.pct}%` : 'n/a';
    const status = r.hardFailures.length > 0 ? `❌ ${r.hardFailures.length}` : '✅ 0';
    const legacyStatus = r.legacyOk ? `${r.legacyStatus}` : `MISSING (${r.legacyStatus ?? 'err'})`;
    const astroStatus = r.astroOk ? `${r.astroStatus}` : `MISSING (${r.astroStatus ?? 'err'})`;
    const jsonLdMatch =
      L && A
        ? JSON.stringify(L.jsonLdTypes) === JSON.stringify(A.jsonLdTypes)
          ? '✅'
          : '❌'
        : 'n/a';
    lines.push(
      `| \`${esc(r.route)}\` | ${legacyStatus} | ${astroStatus} | ${status} | ${textPct} | ${L ? L.h1 : '-'}/${A ? A.h1 : '-'} | ${L ? L.h2 : '-'}/${A ? A.h2 : '-'} | ${L ? L.h3 : '-'}/${A ? A.h3 : '-'} | ${L ? L.internalLinks : '-'}/${A ? A.internalLinks : '-'} | ${jsonLdMatch} | [shots](${shotRel(r.route)}) |`,
    );
  }
  lines.push('');

  lines.push('## Cross-route patterns (aggregated — read this before the per-route detail)');
  lines.push('');
  const titleMismatch = results.filter((r) => r.legacy && r.astro && r.legacy.title !== r.astro.title);
  const descMismatch = results.filter((r) => r.legacy && r.astro && r.legacy.metaDesc !== r.astro.metaDesc);
  const jsonLdMismatch = results.filter(
    (r) => r.legacy && r.astro && JSON.stringify(r.legacy.jsonLdTypes) !== JSON.stringify(r.astro.jsonLdTypes),
  );
  const mainMissingOnAstro = results.filter((r) => r.legacy && r.legacy.main && r.astro && !r.astro.main);
  const droppedTypeCounts = new Map();
  const addedTypeCounts = new Map();
  for (const r of results) {
    if (!r.legacy || !r.astro) continue;
    const L = new Set(r.legacy.jsonLdTypes);
    const A = new Set(r.astro.jsonLdTypes);
    for (const t of L) if (!A.has(t)) droppedTypeCounts.set(t, (droppedTypeCounts.get(t) || 0) + 1);
    for (const t of A) if (!L.has(t)) addedTypeCounts.set(t, (addedTypeCounts.get(t) || 0) + 1);
  }
  const fmtCounts = (m) =>
    [...m.entries()]
      .sort((a, b) => b[1] - a[1])
      .map(([t, n]) => `${t} (${n} route${n === 1 ? '' : 's'})`)
      .join(', ') || 'none';

  lines.push(
    `- **JSON-LD structured data: ${jsonLdMismatch.length}/${totalRoutes} routes lose or change @type coverage** — ` +
      'this is the single most consistent hard failure across the whole ported set, not an isolated bug.',
  );
  lines.push(`  - Types present on LEGACY but absent from ASTRO: ${fmtCounts(droppedTypeCounts)}`);
  lines.push(`  - Types present on ASTRO but absent from LEGACY: ${fmtCounts(addedTypeCounts)}`);
  lines.push(
    '  - Net effect: post/page-level schema (`BlogPosting`, `FAQPage`, `Article`, `DefinedTerm`, `WebSite`, `Blog`) is ' +
      'frequently dropped on Astro in favour of a generic `Organization` block, or `Organization` is added alongside ' +
      'an otherwise-intact set. Either way this is live SEO surface and should be verified against the intended ' +
      'schema design, not assumed to be redesign noise.',
  );
  lines.push(
    `- **\`<title>\` differs on ${titleMismatch.length}/${totalRoutes} routes** — all within \`/blog/\`. Some are ` +
      'additive only (Astro appends " | CrowAgent" where legacy omitted it), but several are substantively reworded ' +
      '(e.g. legacy "Method Statements That Score" vs Astro "How to write a method statement that actually scores"). ' +
      'A reworded `<title>` changes the Google SERP snippet and any inbound backlink anchor expectations — treat the ' +
      'additive and the substantive cases differently when signing off.',
  );
  lines.push(
    `- **Meta description differs on ${descMismatch.length}/${totalRoutes} routes.**`,
  );
  if (mainMissingOnAstro.length > 0) {
    lines.push(
      `- **\`<main>\` landmark is entirely absent on ASTRO for ${mainMissingOnAstro.length}/${totalRoutes} routes** ` +
        `(${mainMissingOnAstro.map((r) => `\`${r.route}\``).join(', ')}) where LEGACY has one. Astro renders these as ` +
        'an `<article>` with no `<main>` wrapper. This is not in the hard-failure list above (it was not one of the ' +
        'agreed hard-fail criteria) but it is a real accessibility regression — screen-reader "skip to main content" ' +
        'and landmark navigation lose their target on every affected route — and should be fixed before cutover ' +
        'regardless.',
    );
  }
  lines.push('');

  lines.push('## Hard failures (true regressions — must fix before cutover)');
  lines.push('');
  if (hardFailRoutes.length === 0) {
    lines.push('None. Every compared route matched on title, description, canonical, JSON-LD @type set, h1 count, and text diff ≤ 2%.');
  } else {
    for (const r of hardFailRoutes) {
      lines.push(`### \`${r.route}\``);
      lines.push('');
      for (const f of r.hardFailures) {
        lines.push(`- ${f}`);
      }
      lines.push('');
      lines.push(`Screenshots: \`${shotRel(r.route)}/legacy.png\` vs \`${shotRel(r.route)}/astro.png\``);
      lines.push('');
    }
  }

  lines.push('## Notable non-failing differences (reported, not blocking — expected for a redesign)');
  lines.push('');
  for (const r of results) {
    if (!r.notes || r.notes.length === 0) continue;
    lines.push(`### \`${r.route}\``);
    lines.push('');
    for (const n of r.notes) lines.push(`- ${n}`);
    lines.push('');
  }

  lines.push('## Verdict');
  lines.push('');
  if (missingRoutes.length > 0) {
    lines.push(
      `**NOT SAFE TO CUT OVER.** ${missingRoutes.length} route(s) failed to load on one side entirely — ` +
        'fix availability before any other judgement is meaningful.',
    );
  } else if (hardFailRoutes.length === 0) {
    lines.push(
      '**SAFE TO CUT OVER** for the 22 ported routes: no title/description/canonical drift, no JSON-LD ' +
        '`@type` loss, every route has exactly one `<h1>`, and visible text differs by ≤2% everywhere. ' +
        'Remaining differences are layout/structure only, consistent with an intentional redesign — review ' +
        'the screenshots for sign-off but they are not blockers.',
    );
  } else {
    lines.push(
      `**NOT SAFE TO CUT OVER YET.** ${hardFailRoutes.length} of ${totalRoutes} routes have ${totalHardFailures} ` +
        'hard-failure finding(s) — see "Hard failures" above. Fix the JSON-LD / metadata / text-loss issues ' +
        'on those routes, re-run the spec, and regenerate this report before replacing any of the affected ' +
        'legacy routes.',
    );
    if (mainMissingOnAstro.length > 0) {
      lines.push(
        `Also fix the missing \`<main>\` landmark on the ${mainMissingOnAstro.length} route(s) noted above before ` +
          'cutover — it is not a hard-fail criterion here but it is a genuine accessibility regression.',
      );
    }
  }
  lines.push('');

  fs.mkdirSync(path.dirname(REPORT_PATH), { recursive: true });
  fs.writeFileSync(REPORT_PATH, lines.join('\n'));
  console.log(`Wrote ${REPORT_PATH}`);
  console.log(
    `routes=${totalRoutes} clean=${cleanRoutes.length} hardFailRoutes=${hardFailRoutes.length} totalHardFailures=${totalHardFailures}`,
  );
}

main();
